package com.example.util

import android.app.Activity
import android.content.Context
import android.content.Intent
import android.content.IntentSender
import android.net.Uri
import com.example.data.model.Paper
import com.example.data.repository.ArchiveRepository
import com.example.data.repository.PdfManager
import com.google.mlkit.vision.documentscanner.GmsDocumentScannerOptions
import com.google.mlkit.vision.documentscanner.GmsDocumentScanning
import com.google.mlkit.vision.documentscanner.GmsDocumentScanningResult
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

class DocumentScannerHelper(private val context: Context) {

    private val repository = ArchiveRepository(context)
    private val pdfManager = PdfManager(context)

    private val scannerOptions: GmsDocumentScannerOptions by lazy {
        GmsDocumentScannerOptions.Builder()
            .setGalleryImportAllowed(true)
            .setPageLimit(100)
            .setResultFormats(
                GmsDocumentScannerOptions.RESULT_FORMAT_PDF,
                GmsDocumentScannerOptions.RESULT_FORMAT_JPEG
            )
            .setScannerMode(GmsDocumentScannerOptions.SCANNER_MODE_FULL)
            .build()
    }

    fun startScanning(
        activity: Activity,
        onIntentSenderReady: (IntentSender) -> Unit,
        onError: (Exception) -> Unit
    ) {
        val scanner = GmsDocumentScanning.getClient(scannerOptions)
        scanner.getStartScanIntent(activity)
            .addOnSuccessListener { intentSender ->
                onIntentSenderReady(intentSender)
            }
            .addOnFailureListener { e ->
                onError(e)
            }
    }

    suspend fun handleScanResult(
        resultData: Intent?,
        paperTitle: String? = null
    ): Result<Paper> = withContext(Dispatchers.IO) {
        try {
            val scanResult = GmsDocumentScanningResult.fromActivityResultIntent(resultData)
                ?: return@withContext Result.failure(Exception("Scan was cancelled or returned empty data."))

            val pdf = scanResult.pdf
                ?: return@withContext Result.failure(Exception("No PDF file generated by scanner."))

            val uri: Uri = pdf.uri
            val timestamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.getDefault()).format(Date())
            val dateDisplay = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault()).format(Date())
            val baseName = "scan_$timestamp"

            val localFile = pdfManager.saveScannedPdf(uri, baseName)
                ?: return@withContext Result.failure(Exception("Failed to save scanned document locally."))

            val title = if (!paperTitle.isNullOrBlank()) {
                paperTitle.trim()
            } else {
                "Scanned Paper ($dateDisplay)"
            }

            val savedPaper = repository.saveScannedPaper(
                title = title,
                file = localFile,
                universityName = "Self Scanned Document",
                subjectName = "Question Paper"
            )

            Result.success(savedPaper)
        } catch (e: Exception) {
            Result.failure(e)
        }
    }
}
